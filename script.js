// Play three short warning beeps.
// This is generated by the browser, so no audio file is required.
// ==========================================
// 30-SECOND ALARM SOUND
// ==========================================

// ==========================================
// 10-SECOND ALARM + SPOKEN WARNING
// ==========================================

function playAlarmSound() {
    const AudioContextClass =
        window.AudioContext || window.webkitAudioContext;

    if (!AudioContextClass) {
        speakSavingsWarning();
        return;
    }

    try {
        const audioContext = new AudioContextClass();

        function startAlarm() {
            const startTime = audioContext.currentTime;
            const duration = 10; // Alarm lasts 10 seconds
            const beepInterval = 0.5; // Beep every half-second

            for (let time = 0; time < duration; time += beepInterval) {
                const oscillator = audioContext.createOscillator();
                const gain = audioContext.createGain();

                const beepStart = startTime + time;
                const beepEnd = beepStart + 0.3;

                oscillator.type = "sawtooth";
                oscillator.frequency.setValueAtTime(880, beepStart);

                gain.gain.setValueAtTime(0.0001, beepStart);
                gain.gain.exponentialRampToValueAtTime(
                    0.15,
                    beepStart + 0.02
                );
                gain.gain.setValueAtTime(0.15, beepEnd - 0.03);
                gain.gain.exponentialRampToValueAtTime(
                    0.0001,
                    beepEnd
                );

                oscillator.connect(gain);
                gain.connect(audioContext.destination);

                oscillator.start(beepStart);
                oscillator.stop(beepEnd);
            }

            // Speak the warning after the 10-second alarm.
            setTimeout(() => {
                audioContext.close().catch(() => {});
                speakSavingsWarning();
            }, 10000);
        }

        if (audioContext.state === "suspended") {
            audioContext.resume()
                .then(startAlarm)
                .catch(error => {
                    console.warn("Could not start the alarm:", error);
                    audioContext.close().catch(() => {});
                    speakSavingsWarning();
                });
        } else {
            startAlarm();
        }

    } catch (error) {
        console.error("Could not play the alarm:", error);
        speakSavingsWarning();
    }
}


// ==========================================
// SPEAK THE SAVINGS WARNING
// ==========================================

function speakSavingsWarning() {
    if (!("speechSynthesis" in window)) {
        console.warn("Speech is not supported by this browser.");
        return;
    }

    // Stop any previous spoken warning.
    window.speechSynthesis.cancel();

    const message = new SpeechSynthesisUtterance(
        "Attention! Your savings are below your target for this month. " +
        "Please control your expenses and save more!"
    );

    message.lang = "en-IN";
    message.rate = 0.9;
    message.pitch = 1;
    message.volume = 1;

    window.speechSynthesis.speak(message);
}

