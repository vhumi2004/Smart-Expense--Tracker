// Format numbers as Indian Rupees.
function formatCurrency(amount) {
    return new Intl.NumberFormat("en-IN", {
        style: "currency",
        currency: "INR",
        minimumFractionDigits: 2,
        maximumFractionDigits: 2
    }).format(amount);
}

// Get today's date using local time.
function getTodayDate() {
    const today = new Date();
    const year = today.getFullYear();
    const month = String(today.getMonth() + 1).padStart(2, "0");
    const day = String(today.getDate()).padStart(2, "0");

    return `${year}-${month}-${day}`;
}

// Get the current month in YYYY-MM format.
function getCurrentMonth() {
    const today = new Date();

    const year = today.getFullYear();
    const month = String(today.getMonth() + 1).padStart(2, "0");

    return `${year}-${month}`;
}

// Save transactions in localStorage.
function saveTransactions() {
    try {
        localStorage.setItem("transactions", JSON.stringify(transactions));
    } catch (error) {
        console.error("Could not save transactions:", error);
        alert("Your transactions could not be saved in this browser.");
    }
}

// Calculate current month's income, expenses, and savings.
function getMonthlyFinancials() {
    const currentMonth = getCurrentMonth();

    let income = 0;
    let expenses = 0;

    transactions.forEach(transaction => {
        if (!transaction.date.startsWith(currentMonth)) {
            return;
        }

        const amount = Number(transaction.amount);

        if (transaction.type === "income") {
            income += amount;
        } else if (transaction.type === "expense") {
            expenses += amount;
        }
    });

    return {
        income,
        expenses,
        savings: income - expenses
    };
}


