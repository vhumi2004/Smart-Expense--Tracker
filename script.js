// Display the current savings status.
function updateSavingsGoal() {
    const financials = getMonthlyFinancials();
    const savings = financials.savings;

    currentMonthSavingsElement.textContent =
        formatCurrency(savings);

    savedTargetDisplay.textContent =
        formatCurrency(savingsTarget);

    const percentage = savingsTarget > 0
        ? (savings / savingsTarget) * 100
        : 0;

    // Keep the progress bar between 0% and 100%.
    const progressPercentage = Math.max(
        0,
        Math.min(100, percentage)
    );

    savingsProgress.style.width = `${progressPercentage}%`;

    if (savings >= savingsTarget) {
        savingsAlert.className = "savings-alert safe-alert";

        savingsAlert.textContent =
            "✅ Your savings are on track! You have met your minimum monthly savings target.";

        savingsProgressLabel.textContent =
            `${Math.round(percentage)}% of your savings target`;

        savingsProgress.style.background = "#22a06b";
    } else {
        const shortfall = savingsTarget - savings;

        savingsAlert.className = "savings-alert warning-alert";

        savingsAlert.textContent =
            `🚨 SAVINGS ALERT! Your monthly savings are below your target of ` +
            `${formatCurrency(savingsTarget)}. ` +
            `Your current savings are ${formatCurrency(savings)}. ` +
            `You need ${formatCurrency(shortfall)} more to reach your target.`;

        savingsProgressLabel.textContent =
            `${Math.max(0, Math.round(percentage))}% of your savings target`;

        savingsProgress.style.background = "#dc2626";
    }
}

// Save the target entered by the user.
saveTargetButton.addEventListener("click", function () {
    const newTarget = Number(savingsTargetInput.value);

    if (!Number.isFinite(newTarget) || newTarget <= 0) {
        alert("Please enter a savings target greater than ₹0.");
        savingsTargetInput.focus();
        return;
    }

    const oldTarget = savingsTarget;

    savingsTarget = newTarget;

    try {
        localStorage.setItem(
            "monthlySavingsTarget",
            String(savingsTarget)
        );
    } catch (error) {
        console.error("Could not save savings target:", error);

        savingsTarget = oldTarget;

        alert("The savings target could not be saved.");
        return;
    }

    updateDashboard();

    alert(
        `Your monthly savings target has been set to ${formatCurrency(savingsTarget)}.`
    );
});

// Check whether savings have crossed below the target.
// The alarm plays only when savings move from at/above the target
// to below it. It does not repeatedly sound while already below.
function checkSavingsCrossing(previousSavings, newSavings) {
    if (
        previousSavings >= savingsTarget &&
        newSavings < savingsTarget
    ) {
        playAlarmSound();
    }
}


// ==========================================
// ADD TRANSACTION
// ==========================================

transactionForm.addEventListener("submit", function (event) {
    event.preventDefault();

    const title = titleInput.value.trim();
    const amount = Number(amountInput.value);
    const type = typeInput.value;
    const category = categoryInput.value;
    const date = dateInput.value;

    if (!title) {
        alert("Please enter a transaction name.");
        titleInput.focus();
        return;
    }

    if (!Number.isFinite(amount) || amount <= 0) {
        alert("Please enter an amount greater than ₹0.");
        amountInput.focus();
        return;
    }

    if (!date) {
        alert("Please select a transaction date.");
        dateInput.focus();
        return;
    }

    // Check savings before adding the transaction.
    const previousSavings = getMonthlyFinancials().savings;

    const transaction = {
        id: (
            Date.now().toString() +
            Math.random().toString(36).slice(2, 8)
        ),
        title,
        amount,
        type,
        category,
        date
    };

    transactions.push(transaction);

    saveTransactions();

    // Check savings after adding the transaction.
    const newSavings = getMonthlyFinancials().savings;

    checkSavingsCrossing(previousSavings, newSavings);

    updateDashboard();
    displayTransactions();

    transactionForm.reset();

    // Default values after resetting.
    typeInput.value = "expense";
    dateInput.value = getTodayDate();
});


// ==========================================
// DASHBOARD TOTALS
// ==========================================

function updateDashboard() {
    let totalIncome = 0;
    let totalExpenses = 0;

    transactions.forEach(transaction => {
        const amount = Number(transaction.amount);

        if (transaction.type === "income") {
            totalIncome += amount;
        } else if (transaction.type === "expense") {
            totalExpenses += amount;
        }
    });

    document.getElementById("total-income").textContent =
        formatCurrency(totalIncome);

    document.getElementById("total-expenses").textContent =
        formatCurrency(totalExpenses);

    document.getElementById("available-balance").textContent =
        formatCurrency(totalIncome - totalExpenses);

    updateSavingsGoal();
    updateExpenseChart();
    updateIncomeExpenseChart();
}


// ==========================================
// TRANSACTION HISTORY
// ==========================================

function displayTransactions() {
    transactionList.replaceChildren();

    if (transactions.length === 0) {
        const emptyMessage = document.createElement("p");

        emptyMessage.className = "empty-message";
        emptyMessage.textContent = "No transactions added yet.";

        transactionList.appendChild(emptyMessage);
        return;
    }

    // Show the newest transactions first.
    const sortedTransactions = [...transactions].sort((a, b) => {
        const dateDifference = b.date.localeCompare(a.date);

        if (dateDifference !== 0) {
            return dateDifference;
        }

        return String(b.id).localeCompare(String(a.id));
    });

    sortedTransactions.forEach(transaction => {
        const item = document.createElement("div");
        item.className = "transaction-item";

        const details = document.createElement("div");
        details.className = "transaction-details";

        const title = document.createElement("h3");
        title.textContent = transaction.title;

        const information = document.createElement("p");
        information.textContent =
            `${transaction.category} • ${transaction.date}`;

        const rightSide = document.createElement("div");
        rightSide.className = "transaction-right";

        const amount = document.createElement("span");

        if (transaction.type === "income") {
            amount.className = "transaction-amount transaction-income";
            amount.textContent = `+ ${formatCurrency(Number(transaction.amount))}`;
        } else {
            amount.className = "transaction-amount transaction-expense";
            amount.textContent = `− ${formatCurrency(Number(transaction.amount))}`;
        }

        const deleteButton = document.createElement("button");
        deleteButton.type = "button";
        deleteButton.className = "delete-button";
        deleteButton.textContent = "Delete";

        deleteButton.addEventListener("click", function () {
            deleteTransaction(transaction.id);
        });

        details.appendChild(title);
        details.appendChild(information);

        rightSide.appendChild(amount);
        rightSide.appendChild(deleteButton);

        item.appendChild(details);
        item.appendChild(rightSide);

        transactionList.appendChild(item);
    });
}


// ==========================================
// DELETE TRANSACTION
// ==========================================

function deleteTransaction(id) {
    const transactionIndex = transactions.findIndex(
        transaction => String(transaction.id) === String(id)
    );

    if (transactionIndex === -1) {
        return;
    }

    const transaction = transactions[transactionIndex];

    const shouldDelete = confirm(
        `Are you sure you want to delete "${transaction.title}"?`
    );

    if (!shouldDelete) {
        return;
    }

    // Check savings before deleting.
    const previousSavings = getMonthlyFinancials().savings;

    transactions.splice(transactionIndex, 1);

    saveTransactions();

    // Check savings after deleting.
    const newSavings = getMonthlyFinancials().savings;

    checkSavingsCrossing(previousSavings, newSavings);

    updateDashboard();
    displayTransactions();
}


// ==========================================
// PIE CHART: EXPENSE BREAKDOWN
// ==========================================

function updateExpenseChart() {
    const canvas = document.getElementById("expense-chart");
    const message = document.getElementById("chart-message");
    const currentMonth = getCurrentMonth();

    const categoryTotals = {};

    transactions.forEach(transaction => {
        if (
            transaction.type !== "expense" ||
            !transaction.date.startsWith(currentMonth)
        ) {
            return;
        }

        const category = transaction.category || "Other";

        categoryTotals[category] =
            (categoryTotals[category] || 0) +
            Number(transaction.amount);
    });

    const labels = Object.keys(categoryTotals);
    const values = Object.values(categoryTotals);

    if (expenseChart) {
        expenseChart.destroy();
        expenseChart = null;
    }

    if (labels.length === 0) {
        message.textContent =
            "No expenses recorded for the current month yet.";

        return;
    }

    message.textContent = "";

    expenseChart = new Chart(canvas, {
        type: "doughnut",

        data: {
            labels: labels,

            datasets: [{
                label: "Expenses",
                data: values,
                backgroundColor: [
                    "#4263eb",
                    "#f76707",
                    "#12b886",
                    "#e64980",
                    "#7950f2",
                    "#fab005",
                    "#15aabf",
                    "#868e96",
                    "#d9480f",
                    "#74b816"
                ],
                borderWidth: 2,
                borderColor: "#ffffff"
            }]
        },

        options: {
            responsive: true,
            maintainAspectRatio: false,

            plugins: {
                legend: {
                    position: "bottom"
                },

                tooltip: {
                    callbacks: {
                        label: function (context) {
                            return `${context.label}: ${formatCurrency(context.raw)}`;
                        }
                    }
                }
            }
        }
    });
}


// ==========================================
// BAR CHART: INCOME VS EXPENSES
// ==========================================

function updateIncomeExpenseChart() {
    const canvas = document.getElementById("income-expense-chart");
    const message = document.getElementById("bar-chart-message");

    const financials = getMonthlyFinancials();

    if (incomeExpenseChart) {
        incomeExpenseChart.destroy();
        incomeExpenseChart = null;
    }

    if (financials.income === 0 && financials.expenses === 0) {
        message.textContent =
            "Add income or expense transactions to display the monthly comparison.";

        return;
    }

    message.textContent = "";

    incomeExpenseChart = new Chart(canvas, {
        type: "bar",

        data: {
            labels: ["Income", "Expenses"],

            datasets: [{
                label: "Amount (₹)",
                data: [
                    financials.income,
                    financials.expenses
                ],

                backgroundColor: [
                    "#22a06b",
                    "#e05252"
                ],

                borderRadius: 7,
                maxBarThickness: 90
            }]
        },

        options: {
            responsive: true,
            maintainAspectRatio: false,

            scales: {
                y: {
                    beginAtZero: true,

                    ticks: {
                        callback: function (value) {
                            return "₹" + Number(value).toLocaleString("en-IN");
                        }
                    }
                }
            },

            plugins: {
                legend: {
                    display: false
                },

                tooltip: {
                    callbacks: {
                        label: function (context) {
                            return formatCurrency(context.raw);
                        }
                    }
                }
            }
        }
    });
}


