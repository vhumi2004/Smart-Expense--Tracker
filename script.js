// Load saved transactions from the browser.
let transactions = [];

try {
    const savedTransactions = localStorage.getItem("transactions");
    const parsedTransactions = JSON.parse(savedTransactions || "[]");

    if (Array.isArray(parsedTransactions)) {
        transactions = parsedTransactions.filter(transaction =>
            transaction &&
            typeof transaction === "object" &&
            Number.isFinite(Number(transaction.amount)) &&
            Number(transaction.amount) > 0 &&
            ["income", "expense"].includes(transaction.type) &&
            typeof transaction.date === "string"
        );
    }
} catch (error) {
    console.error("Could not load saved transactions:", error);
    transactions = [];
}

// Load the monthly savings target.
let savingsTarget = 5000;

try {
    const savedTarget = Number(localStorage.getItem("monthlySavingsTarget"));

    if (Number.isFinite(savedTarget) && savedTarget > 0) {
        savingsTarget = savedTarget;
    }
} catch (error) {
    console.error("Could not load savings target:", error);
}

